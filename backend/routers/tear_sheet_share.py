"""Tear Sheet sharing — Research → Tear Sheet → Download PDF / Email.

  GET  /api/tear-sheet/{symbol}/pdf     the tear sheet as a PDF download
  POST /api/tear-sheet/{symbol}/email   email it (PDF attached) via SMTP
  GET  /api/tear-sheet-share/status     whether email is configured (drives the UI)

Both use routers.tear_sheet.load_tear_sheet, i.e. the same cached data the page shows, and
tear_sheet_pdf.build_pdf, so the file a recipient gets matches the download exactly.

The API has no login, so emailing is deliberately opt-in and bounded: nothing is sent until
SMTP is configured in backend/.env, recipients per message and sends per hour are capped, and
EMAIL_ALLOWED_RECIPIENTS can restrict who may receive mail (see email_sender.py).
"""
import asyncio
import re
from html import escape

from fastapi import APIRouter, HTTPException
from fastapi.responses import Response
from pydantic import BaseModel, Field

import email_sender
from routers.tear_sheet import load_tear_sheet
from tear_sheet_pdf import build_pdf

router = APIRouter()

_SYMBOL_RE = re.compile(r"^[A-Z0-9.\-^=]{1,12}$")


class EmailRequest(BaseModel):
    to: str | list[str]
    note: str = Field("", max_length=1000)


def _fmt_money(n):
    return "—" if n is None else f"${n:,.2f}"


def _vs_fair(premium: float) -> str:
    """premium is price / fair value - 1, so positive means the stock trades above fair value."""
    return f"{abs(premium) * 100:.0f}% {'above' if premium >= 0 else 'below'} fair value"


def pdf_filename(sheet: dict) -> str:
    return f"{sheet['symbol']}_TearSheet_{sheet.get('asOf', '')}.pdf"


def compose_email(sheet: dict, note: str = "") -> tuple[str, str, str]:
    """(subject, plain text, html) summarising the sheet; the PDF carries the detail."""
    sym = sheet["symbol"]
    name = sheet["profile"].get("name") or sym
    price = sheet["snapshot"].get("price")
    v = sheet["valuation"]["verdict"]
    score = sheet["scorecard"].get("overall")
    strengths, risks = sheet["flags"]["strengths"][:3], sheet["flags"]["risks"][:3]
    subject = f"{sym} tear sheet: {v['label']} (as of {sheet.get('asOf', '')})"

    lines = []
    if note.strip():
        lines += [note.strip(), "", "-" * 40, ""]
    lines += [f"{name} ({sym}) - {_fmt_money(price)}", f"Valuation: {v['label']}"]
    if v.get("fairValue") is not None:
        lines.append(f"Blended fair value {_fmt_money(v['fairValue'])} - the price is {_vs_fair(v['premium'])} "
                     f"(model range {_fmt_money(v['low'])} - {_fmt_money(v['high'])})")
    if score is not None:
        lines.append(f"Overall score: {score:.0f} / 100")
    if strengths:
        lines += ["", "Strengths:"] + [f"  + {s}" for s in strengths]
    if risks:
        lines += ["", "Risks to weigh:"] + [f"  - {r}" for r in risks]
    lines += ["", "The full tear sheet is attached as a PDF.", "",
              "Generated by StockMonitor from Yahoo Finance and SEC EDGAR data. A rules-based screen, not investment advice."]
    text = "\n".join(lines)

    def li(items, color):
        return "".join(f'<li style="color:{color}">{escape(i)}</li>' for i in items)
    html = ['<div style="font-family:Arial,Helvetica,sans-serif;font-size:14px;color:#111827;max-width:560px">']
    if note.strip():
        html.append(f'<p style="white-space:pre-wrap">{escape(note.strip())}</p><hr style="border:0;border-top:1px solid #d1d5db">')
    html.append(f'<h2 style="margin:0 0 2px">{escape(sym)} <span style="font-weight:normal;color:#6b7280">{escape(name)}</span></h2>')
    html.append(f'<p style="margin:0 0 10px">{escape(_fmt_money(price))} &middot; <b>{escape(v["label"])}</b>')
    if v.get("fairValue") is not None:
        html.append(f'<br>Blended fair value {escape(_fmt_money(v["fairValue"]))} - the price is {escape(_vs_fair(v["premium"]))}')
    if score is not None:
        html.append(f'<br>Overall score {score:.0f} / 100')
    html.append("</p>")
    if strengths:
        html.append(f'<b style="color:#059669">Strengths</b><ul style="margin:2px 0 8px">{li(strengths, "#111827")}</ul>')
    if risks:
        html.append(f'<b style="color:#dc2626">Risks to weigh</b><ul style="margin:2px 0 8px">{li(risks, "#111827")}</ul>')
    html.append('<p style="color:#6b7280;font-size:12px">The full tear sheet is attached as a PDF. Generated by StockMonitor from '
                'Yahoo Finance and SEC EDGAR data; a rules-based screen, not investment advice.</p></div>')
    return subject, text, "".join(html)


async def _sheet_or_404(symbol: str) -> dict:
    sym = symbol.upper().strip()
    if not _SYMBOL_RE.match(sym):
        raise HTTPException(400, "Invalid ticker symbol")
    sheet = await load_tear_sheet(sym)
    if sheet.get("error"):
        raise HTTPException(404, sheet["error"])
    return sheet


@router.get("/api/tear-sheet-share/status")
def share_status():
    return {"emailConfigured": email_sender.EMAIL.configured(), "maxRecipients": email_sender.MAX_RECIPIENTS}


@router.get("/api/tear-sheet/{symbol}/pdf")
async def tear_sheet_pdf(symbol: str):
    sheet = await _sheet_or_404(symbol)
    loop = asyncio.get_event_loop()
    pdf = await loop.run_in_executor(None, lambda: build_pdf(sheet))
    return Response(content=pdf, media_type="application/pdf",
                    headers={"Content-Disposition": f'attachment; filename="{pdf_filename(sheet)}"'})


@router.post("/api/tear-sheet/{symbol}/email")
async def email_tear_sheet(symbol: str, body: EmailRequest):
    if not email_sender.EMAIL.configured():
        raise HTTPException(503, "Email isn't set up yet. Add SMTP_HOST, SMTP_USER and SMTP_PASSWORD to backend/.env and restart the backend.")
    recipients, invalid = email_sender.parse_recipients(body.to)
    if invalid:
        raise HTTPException(400, f"Not a valid email address: {', '.join(invalid[:3])}")
    if not recipients:
        raise HTTPException(400, "Enter at least one email address")
    if len(recipients) > email_sender.MAX_RECIPIENTS:
        raise HTTPException(400, f"At most {email_sender.MAX_RECIPIENTS} recipients per message")
    blocked = email_sender.disallowed_recipients(recipients)
    if blocked:
        raise HTTPException(403, f"Not on the allowed-recipients list (EMAIL_ALLOWED_RECIPIENTS): {', '.join(blocked[:3])}")
    if email_sender.rate_limited():
        raise HTTPException(429, f"Email limit reached ({email_sender.MAX_SENDS_PER_HOUR} per hour). Try again later.")

    sheet = await _sheet_or_404(symbol)
    loop = asyncio.get_event_loop()
    pdf = await loop.run_in_executor(None, lambda: build_pdf(sheet))
    subject, text, html = compose_email(sheet, body.note)
    result = await loop.run_in_executor(
        None, lambda: email_sender.EMAIL.send(recipients, subject, text, html,
                                              ((pdf_filename(sheet), pdf, "application/pdf"),)))
    if not result["ok"]:
        raise HTTPException(502, result["error"])
    return {"ok": True, "sent": recipients, "filename": pdf_filename(sheet)}
